async function assertLayout(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  const overflows = await page.locator('[data-route-binding], [data-route-group], [role="dialog"]').evaluateAll((elements) => elements.filter((element) => element.scrollWidth > element.clientWidth + 1).map((element) => element.getAttribute('data-route-binding') || element.getAttribute('data-route-group') || 'dialog'))
  expect(overflows).toEqual([])
}

