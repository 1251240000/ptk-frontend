import { expect, test, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { installMockApi } from './mock-api'

const api = process.env.PARTOKENS_ROUTE_TEST_API || 'http://127.0.0.1:8082'
const evidence = process.env.PARTOKENS_ROUTE_TEST_EVIDENCE || '../../dogfood-output/2026-09-11-group-route-inline'
const headers = { Authorization: 'Bearer root-token' }

async function setup(page: Page) {
  const reset = await page.request.post(`${api}/__test/reset`)
  expect(reset.ok()).toBeTruthy()
  await installMockApi(page, { role: 100 })
  await page.route('**/admin-api/**', async (route) => {
    const path = new URL(route.request().url()).pathname.replace('/admin-api', '')
    const response = await route.fetch({ url: `${api}${path}`, headers: { ...route.request().headers(), ...headers } })
    await route.fulfill({ response })
  })
  await page.goto('/zh-CN/console/admin/routes')
  await expect(page.getByRole('table', { name: '分组路由总览' })).toBeVisible()
}

async function save(page: Page) {
  await page.getByRole('button', { name: '预览变更', exact: true }).click()
  const dialog = page.getByRole('dialog').last()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '确认保存', exact: true }).click()
  return dialog
}

async function addChannel(page: Page, name: string) {
  await page.getByRole('button', { name: '添加渠道', exact: true }).click()
  const selector = page.getByRole('button', { name: '选择渠道', exact: true }).last()
  await expect(selector).toBeFocused()
  await selector.click()
  await expect(page.getByRole('combobox', { name: '搜索渠道' })).toBeFocused()
  await page.getByRole('combobox', { name: '搜索渠道' }).fill(name)
  await page.getByRole('option').filter({ has: page.getByText(name, { exact: true }) }).click()
  await expect(page.getByRole('textbox', { name: '搜索已绑定渠道' })).toHaveValue('')
}

