function ProviderLogo({ provider }: { provider: Provider }): ReactNode {
  return (
    <span className={`flex size-[18px] shrink-0 items-center justify-center ${provider.className}`} title={provider.label} aria-label={provider.label}>
      <svg viewBox="0 0 24 24" className="size-[18px]" fill="currentColor" shapeRendering="geometricPrecision" aria-hidden="true"><path d={provider.path} /></svg>
    </span>
  )
}

export function ModelProviderIcon({ name }: { name: string }) {
  const provider = providers.find((entry) => entry.provider.label === name)?.provider
  return provider ? <ProviderLogo provider={provider} /> : <Bot className="size-4 text-muted-foreground" aria-hidden="true" />
}

export function ModelProviderBadge({ model }: { model?: string }) {
  if (!model) return <span>—</span>
  const normalized = model.toLowerCase()
  const provider = providers.find((entry) => entry.match(normalized))?.provider
  return (
    <Badge variant="outline" className="max-w-full justify-start gap-1.5 bg-muted/20 px-2 py-1 font-mono font-normal text-foreground" title={model}>
      {provider ? <ProviderLogo provider={provider} /> : <Bot className="size-4 shrink-0 text-muted-foreground" aria-hidden="true" />}
      <span className="truncate">{model}</span>
    </Badge>
  )
}
